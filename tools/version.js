#!/usr/bin/env node
// The game's version: 0.3.<commit count>, the commit count being the commit that carries it (git rev-list --count HEAD).
// Written into src/version.js (the title screen and the run logs read it, also from file://) and package.json's version.
//   node tools/version.js            print the version
//   node tools/version.js --next     write the version of the commit being made (count + 1); with --stage (the pre-commit
//                                    hook) also stage it
//   node tools/version.js --check    fail when the files don't say 0.3.<count> (no git, e.g. a deployed release: passes)
//   node tools/version.js --install  install the pre-commit hook (deploy/pre-commit) into this clone's .git/hooks
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const MAJOR_MINOR = '0.3';   // raise by hand at a milestone; the patch is always the commit count
const FILE = path.join(ROOT, 'src', 'version.js');

const git = (...args) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
function commitCount() { try { return Number(git('rev-list', '--count', 'HEAD')); } catch (e) { return null; } }
function current() { try { return /LUMENHOLD_VERSION = '([^']+)'/.exec(fs.readFileSync(FILE, 'utf8'))[1]; } catch (e) { return null; } }

const setVersion = (text, version) => text.replace(/^(  "version": ")[^"]*(")/m, '$1' + version + '$2');
function write(version, stage) {
  fs.writeFileSync(FILE, "// Generated by tools/version.js (the pre-commit hook): 0.3.<commit count>. Do not edit.\n" +
    "(function (root) { root.LUMENHOLD_VERSION = '" + version + "'; if (typeof module !== 'undefined') module.exports = root.LUMENHOLD_VERSION; })(typeof window !== 'undefined' ? window : globalThis);\n");
  const pkg = path.join(ROOT, 'package.json');
  fs.writeFileSync(pkg, setVersion(fs.readFileSync(pkg, 'utf8'), version));
  if (!stage) return;
  git('add', 'src/version.js');
  // package.json: only its version line is staged (the staged copy with the new version), so unfinished edits to it
  // elsewhere in the file stay out of the commit.
  let staged; try { staged = git('show', ':package.json') + '\n'; } catch (e) { return; }
  const blob = execFileSync('git', ['hash-object', '-w', '--stdin'], { cwd: ROOT, input: setVersion(staged, version), encoding: 'utf8' }).trim();
  git('update-index', '--cacheinfo', '100644,' + blob + ',package.json');
}

const arg = process.argv[2];
if (arg === '--next') {
  const n = commitCount();
  const version = MAJOR_MINOR + '.' + ((n || 0) + 1);
  write(version, process.argv.includes('--stage'));
  console.log(version);
} else if (arg === '--check') {
  const n = commitCount();
  if (n == null) { console.log('version: ' + current() + ' (no git to check against)'); process.exit(0); }
  const want = MAJOR_MINOR + '.' + n, have = current();
  if (have !== want) { console.error('version: src/version.js says ' + have + ', HEAD is commit ' + n + ' (' + want + '). Install the hook: node tools/version.js --install'); process.exit(1); }
  console.log('version: ' + have);
} else if (arg === '--install') {
  const hooks = path.join(git('rev-parse', '--git-common-dir'), 'hooks');
  const dir = path.isAbsolute(hooks) ? hooks : path.join(ROOT, hooks);
  fs.mkdirSync(dir, { recursive: true });
  fs.copyFileSync(path.join(ROOT, 'deploy', 'pre-commit'), path.join(dir, 'pre-commit'));
  fs.chmodSync(path.join(dir, 'pre-commit'), 0o755);
  console.log('installed ' + path.join(dir, 'pre-commit'));
} else {
  console.log(current());
}
