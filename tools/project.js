/*
 * Project file access shared by the CLI (tools/grim.js), the content tools (rename, migrate) and the
 * server. Everything takes a root directory, so tests can point it at a fixture project.
 *
 *   const P = project('/path/to/lifesim');
 *   P.compileAll()  -> { sources, content, errors }      (content/**\/*.grim, core/ first)
 *   P.bundleText()  -> the text of build/content.bundle.js (sources + every locale)
 *   P.contentHash() -> fingerprint of the English sources (stamped on run logs and snapshots)
 */
'use strict';
const fs = require('fs');
const path = require('path');
const G = require('../src/grimoire.js');
const I18n = require('../src/i18n.js');

function listFiles(dir, ext = '.grim') {
  let out = [];
  if (!fs.existsSync(dir)) return out;
  for (const f of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) out = out.concat(listFiles(p, ext));
    else if (f.name.endsWith(ext)) out.push(p);
  }
  return out;
}

function project(root) {
  root = path.resolve(root);
  const CONTENT = path.join(root, 'content');
  const LOCALES = path.join(root, 'locales');
  const rel = (f) => path.relative(root, f).split(path.sep).join('/');
  const abs = (p) => (path.isAbsolute(p) ? p : path.join(root, p));
  function localeLangs() { return fs.existsSync(LOCALES) ? fs.readdirSync(LOCALES, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort() : []; }
  function loadLocaleSources(lang) { return listFiles(path.join(LOCALES, lang), '.lang').map((f) => ({ path: rel(f), text: fs.readFileSync(f, 'utf8') })); }
  function contentFiles() {
    // core/ first so @game/@resource/@skill are defined before everything else
    return listFiles(CONTENT).sort((a, b) => {
      const ca = a.includes(path.sep + 'core' + path.sep) ? 0 : 1, cb = b.includes(path.sep + 'core' + path.sep) ? 0 : 1;
      return ca - cb || a.localeCompare(b);
    });
  }
  function loadSources() { return contentFiles().map((f) => ({ path: rel(f), text: fs.readFileSync(f, 'utf8') })); }
  function compileAll() {
    const sources = loadSources();
    const { content, errors } = G.compile(sources);
    return { sources, content, errors };
  }
  function contentHash(sources) { return I18n.hash((sources || loadSources()).map((x) => x.path + '\n' + x.text).join('\n')); }
  function bundleText(sources) {
    const locales = {};
    for (const lang of localeLangs()) locales[lang] = loadLocaleSources(lang).filter((s) => !s.path.endsWith('/_obsolete.lang'));
    return {
      text: '// GENERATED by `node tools/grim.js build` — do not edit. Sources: content/**/*.grim, locales/**/*.lang\n' +
        'window.LUMENHOLD_SOURCES = ' + JSON.stringify(sources || loadSources(), null, 0) + ';\n' +
        'window.LUMENHOLD_LOCALES = ' + JSON.stringify(locales, null, 0) + ';\n',
      locales,
    };
  }
  return { root, CONTENT, LOCALES, rel, abs, listFiles, localeLangs, loadLocaleSources, contentFiles, loadSources, compileAll, contentHash, bundleText };
}

module.exports = { project, listFiles };
