// Regression goldens for the combat core: the behaviour of the rules and the search, frozen when the JS oracle was retired
// (F5.2; the core matched it on every transition, UI query and search). One golden file, two engines checked against it:
// the native simulator (rust/target/release/combat-sim) and the browser build (web/core.mjs + core.wasm).
//   node tools/golden.mjs           check (after tools/build.mjs)
//   node tools/golden.mjs update    refresh after an intended rule or search change, in the same commit, like `grim snapshot`
// Fights are stored as setup options + actions, so setup (setup/setup.mjs) stays JS and the goldens stay small.
import fs from 'node:fs';import path from 'node:path';import crypto from 'node:crypto';import {spawnSync} from 'node:child_process';import {fileURLToPath} from 'node:url';
import * as R from '../setup/roster.mjs';
import {createState} from '../setup/setup.mjs';
import * as C from '../web/core.mjs';
import {positions} from './positions.mjs';

const root=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const BIN=path.join(root,'rust/target/release/combat-sim'),FILE=path.join(root,'test/golden.json'),RUST_FIGHTS=path.join(root,'rust/core/tests/fights.jsonl');
const update=process.argv[2]==='update';
const E={...R,createState,...C};
const hash=x=>crypto.createHash('sha1').update(typeof x==='string'?x:JSON.stringify(x)).digest('hex').slice(0,12);
// Native lines and wasm results compared as plain JSON (serde prints 1.0 where JS prints 1), timing fields removed.
const norm=line=>{const v=JSON.parse(line);delete v.elapsedMs;return v;};
const start=s=>{const {lastEvents,...rest}=s;return rest;};
const publicState=s=>{const p=JSON.parse(JSON.stringify(s));delete p.lastEvents;delete p.searching;return p;};
function native(cmd,lines){
 const run=spawnSync(BIN,[cmd],{input:lines.map(l=>JSON.stringify(l)).join('\n')+'\n',maxBuffer:2**31-1,encoding:'utf8'});
 if(run.status!==0)throw Error('combat-sim failed: '+run.stderr);
 return run.stdout.trim().split('\n');
}

let rng=0x5eed1234;const rand=()=>{rng=(rng+0x6D2B79F5)|0;let t=Math.imul(rng^(rng>>>15),1|rng);t=(t+Math.imul(t^(t>>>7),61|t))^t;return((t^(t>>>14))>>>0)/4294967296;};
const pick=xs=>xs[Math.floor(rand()*xs.length)];
// Varied setups: generic and named kits, levels 20–80, all-spell access, observers, both health models, depleted budgets, scales.
function setups(n){
 const generic=Object.keys(R.LOADOUTS),named=Object.keys(R.NAMED_LOADOUTS),out=[];
 for(let f=0;f<n;f++){
  const pool=f%5===4?named:generic,lv=()=>20+Math.floor(rand()*61);
  out.push({playerLoadout:pick(pool),opponentLoadout:pick(pool),playerLevel:lv(),opponentLevel:lv(),spellAccess:f%3===0?'kit':'all',firstLeader:f%2,
   observers:f%4===0,healthModel:f%3===1?'offset':'direct',resourceBudget:f%7===0?'depleted':'standard',context:pick(Object.keys(R.CONTEXTS)),
   manaCostScale:f%11===0?1.5:1,hpScale:f%13===0?.5:1,damageMultiplier:f%17===0?.5:1,combatScale:f%19===0?1.25:1});
 }
 return out;
}
// Random legal play (some fights passive, so decisions on points and stalemates occur; some conceded).
function playRandom(opts,i){
 const s=createState(opts),actions=[];
 const passive=i%6===5,concedeAt=i%9===4?3+Math.floor(rand()*12):Infinity;
 while(!s.result&&s.round<=90){
  if(s.round>=concedeAt&&s.pending.every(p=>p===null)){const side=Math.floor(rand()*2);actions.push('concede:'+side);C.concede(s,side);break;}
  const legal=C.legalActions(s),id=passive&&legal.includes('guard')&&rand()<.93?'guard':pick(legal);actions.push(id);C.applyChoice(s,id);
 }
 return actions;
}
const ACTIONS=['strike','guard','reclaim','hold','release','frozen','cancel',...Object.keys(R.SPELLS)];
const EFFECTS=['guard','ward','brace','foreAim','haste','shadowstep','tailwind','reflect','torment','eclipse','heartprice','compelled','lodestar'];
// Everything the UI asks about a state, both sides.
function queries(s){
 const out=[C.actorToMove(s)];
 for(const side of [0,1]){out.push(C.legalActions(s,side));for(const k of EFFECTS)out.push(C.has(s,side,k));
  for(const id of [...ACTIONS,...C.legalActions(s,side).filter(a=>a.startsWith('bundle:'))])out.push(C.available(s,side,id),C.cost(s,side,id),C.hpCost(s,side,id),C.describe(s,side,id));}
 return out;
}

const old=update?null:JSON.parse(fs.readFileSync(FILE,'utf8'));
const g={rulesVersion:C.RULES_VERSION,note:'Generated by tools/golden.mjs update; hashes of the core\'s outputs.',fights:[],search:[],ai:[]};
let bad=0,t0=performance.now();const report=(label,ok,total)=>{console.log(`${ok===total?'ok  ':'FAIL'} ${label}: ${ok}/${total}  (${((performance.now()-t0)/1000).toFixed(0)} s)`);if(ok!==total)bad++;};

// 1. Transitions: native step lines (every applyChoice result, state and legal list) and, for the first fights, the wasm path with every UI query.
const fightSetups=update?setups(160).map((opts,i)=>{try{createState(opts);return opts;}catch{return null;}}).filter(Boolean):old.fights.map(f=>f.opts);
const fights=fightSetups.map((opts,i)=>({opts,actions:update?playRandom(opts,i):old.fights[i].actions}));
const lines=native('step',fights.map(f=>({state:start(createState(f.opts)),actions:f.actions})));
let at=0,nativeOk=0,wasmOk=0,wasmTotal=0;
for(const [i,f] of fights.entries()){
 const steps=f.actions.map(()=>hash(norm(lines[at++])));
 let wasmSteps=null;
 if(i<40){wasmTotal++;const s=createState(f.opts);wasmSteps=[];
  for(const id of f.actions){
   // A stored action that is no longer legal is a difference, not a crash.
   try{const q=queries(s);let applied=null;
    if(id.startsWith('concede:'))C.concede(s,Number(id.slice(8)));else applied=C.applyChoice(s,id);
    wasmSteps.push(hash({q,applied,state:publicState(s)}));}catch(e){wasmSteps.push('error:'+e.message.replace(/\s+/g,'_'));break;}}}
 g.fights.push({opts:f.opts,actions:f.actions,native:steps.join(' '),...(wasmSteps?{wasm:wasmSteps.join(' ')}:{})});
 if(!update){const o=old.fights[i];
  if(o.native===g.fights[i].native)nativeOk++;else if(bad<3)console.log(`   fight ${i}: native differs first at step ${steps.findIndex((h,k)=>h!==o.native.split(' ')[k])}`);
  if(wasmSteps){if(o.wasm===g.fights[i].wasm)wasmOk++;else console.log(`   fight ${i}: wasm differs first at step ${wasmSteps.findIndex((h,k)=>h!==o.wasm.split(' ')[k])}`);}}
}
const steps=fights.reduce((n,f)=>n+f.actions.length,0);
if(!update){report(`transitions, native (${steps} steps)`,nativeOk,fights.length);report('transitions + every UI query, WebAssembly',wasmOk,wasmTotal);}

// 2. Search on the 84 positions: cache off and on, fixed and tactical horizons, with and without pruning, ranked at odd depths.
const P=await positions(E),cases=[];
for(const p of P)for(let d=1;d<=3;d++)for(const prune of [false,true])for(const horizonMode of ['fixed','tactical'])for(const table of [false,true])cases.push({p,options:{maxDepth:d,nodeBudget:1e9,prune,horizonMode,rankActions:d%2===1,table}});
const sr=native('search',cases.map(c=>({state:c.p.state,options:c.options})));
let searchOk=0,wasmSearchOk=0,wasmSearchTotal=0;
cases.forEach((c,i)=>{const r=norm(sr[i]),h=hash(r);g.search.push({id:c.p.id,options:c.options,best:r.id,value:r.value,hash:h});
 if(c.options.maxDepth<=2&&!c.options.table){wasmSearchTotal++;const w=C.searchAction(C.cloneState(c.p.state),c.options);delete w.elapsedMs;if(hash(w)===h)wasmSearchOk++;}
 if(!update){const o=old.search[i];if(o.hash===h)searchOk++;else if(searchOk+4>i)console.log(`   ${c.p.id} ${JSON.stringify(c.options)}: was ${o.best} ${o.value}, now ${r.id} ${r.value}`);}});
if(!update)report(`search on ${P.length} positions`,searchOk,cases.length);
report('search, WebAssembly identical to native (depth ≤ 2, cache off)',wasmSearchOk,wasmSearchTotal);

// 3. Seeded fallible AI fights at depth 3 with the transposition table: identical decisions natively and in WebAssembly.
const G=Object.keys(R.LOADOUTS),aiCases=[];
for(let i=0;i<24;i++){const level=[20,50,80][i%3];aiCases.push({playerLoadout:G[i%9],opponentLoadout:G[(i*4+1)%9],playerLevel:level,opponentLevel:level,firstLeader:i%2,ai:[{profile:'fallible',seed:i*2+1},{profile:'fallible',seed:i*2+2}]});}
const search={maxDepth:3,nodeBudget:200000,prune:true};
const af=native('fight',aiCases.map(o=>({state:start(createState(o)),search,tableLimit:4096,maxRounds:120})));
let aiOk=0,aiWasm=0;
aiCases.forEach((o,i)=>{const r=norm(af[i]),h=hash(r);g.ai.push({opts:o,actions:r.actions.length,hash:h});
 if(i<8){const s=createState(o),ctx=[C.createSearchContext({tableLimit:4096}),C.createSearchContext({tableLimit:4096})],acts=[];
  while(!s.result&&s.round<=120){const d=C.chooseAIAction(s,search,ctx[C.actorToMove(s)]);acts.push(d.id);C.applyChoice(s,d.id);}
  if(JSON.stringify(acts)===JSON.stringify(r.actions))aiWasm++;ctx.forEach(C.freeSearchContext);}
 if(!update&&old.ai[i].hash===h)aiOk++;});
if(!update)report('seeded AI fights, native',aiOk,aiCases.length);
report('seeded AI fights, WebAssembly identical to native',aiWasm,8);

if(update){
 fs.mkdirSync(path.dirname(FILE),{recursive:true});fs.writeFileSync(FILE,JSON.stringify(g,null,0).replace(/\},\{/g,'},\n{')+'\n');
 // A small pure-Rust regression set for `cargo test`: start states, actions and the final state.
 const sample=fights.filter((_,i)=>i%12===0).map(f=>{const s=createState(f.opts);for(const id of f.actions)id.startsWith('concede:')?C.concede(s,Number(id.slice(8))):C.applyChoice(s,id);return JSON.stringify({state:start(createState(f.opts)),actions:f.actions,final:publicState(s)});});
 fs.mkdirSync(path.dirname(RUST_FIGHTS),{recursive:true});fs.writeFileSync(RUST_FIGHTS,sample.join('\n')+'\n');
 console.log(`wrote ${path.relative(root,FILE)}: ${fights.length} fights (${steps} steps), ${cases.length} searches, ${aiCases.length} AI fights; ${path.relative(root,RUST_FIGHTS)}: ${sample.length} fights`);
}else if(old.rulesVersion!==C.RULES_VERSION)console.log(`note: goldens are from ${old.rulesVersion}, core is ${C.RULES_VERSION}`);
if(bad)process.exitCode=1;
