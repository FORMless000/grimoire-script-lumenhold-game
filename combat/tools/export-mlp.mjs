// The Engine eval's weights: a fitted MLP (combat/lab/fit.py, key MLPd16 by default) → rust/core/src/neural_weights.rs, which
// the core compiles in (a .rs file, so the bundle hash sees a change).
//   node tools/export-mlp.mjs <fit.json> [key]     e.g. node tools/export-mlp.mjs out/lab/fit-r0.json MLPd16
// Refit after a rules change that moves fights: (cd lab && cargo build --release), node tools/lab.mjs sample, python3 lab/fit.py.
import fs from 'node:fs';
const [file,key='MLPd16']=process.argv.slice(2);
if(!file){console.error('usage: node tools/export-mlp.mjs <fit.json> [key]');process.exit(2);}
const m=JSON.parse(fs.readFileSync(file,'utf8'))[key];
if(!m)throw Error(`no ${key} in ${file}`);
const arr=a=>'['+a.map(x=>{const s=String(x);return /[.eE]/.test(s)?s:s+'.0';}).join(', ')+']';
const out=new URL('../rust/core/src/neural_weights.rs',import.meta.url);
fs.writeFileSync(out,`// Generated by tools/export-mlp.mjs from ${file.split('/').pop()} (${key}); do not edit by hand.
pub const H: usize = ${m.h};
pub const XS: [f64; ${m.xs.length}] = ${arr(m.xs)};
pub const SM: [f64; ${m.sm.length}] = ${arr(m.sm)};
pub const SS: [f64; ${m.ss.length}] = ${arr(m.ss)};
pub const W1: [f64; ${m.w1.length}] = ${arr(m.w1)};
pub const B1: [f64; ${m.b1.length}] = ${arr(m.b1)};
pub const W2: [f64; ${m.w2.length}] = ${arr(m.w2)};
pub const SCALE: f64 = ${m.scale};
`);
console.log('wrote',out.pathname,`${m.h} hidden units`);
