// node crux/build-wasm.js [--check]
// Builds the page's engine: the data (rust/export-data.js), then the Rust core compiled to WebAssembly (rust/wasm), and
// writes it into crux-wasm.js, base64 in a classic script, so the page works from file:// (no fetch). Rerun after any
// change in rust/ or in the data files. Needs cargo and the wasm32-unknown-unknown target. --check: only says whether
// crux-wasm.js is stale.
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const { execFileSync } = require('child_process');
const here = __dirname, rust = path.join(here, 'rust'), out = path.join(here, 'crux-wasm.js');

// What the build depends on: every source and data file of the core and the wasm crate.
function sources() {
  const files = [];
  const walk = (d) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else files.push(p); } };
  for (const d of ['core/src', 'core/data', 'wasm/src']) walk(path.join(rust, d));
  files.push(path.join(rust, 'Cargo.toml'), path.join(rust, 'Cargo.lock'), path.join(rust, 'core/Cargo.toml'), path.join(rust, 'wasm/Cargo.toml'));
  const h = crypto.createHash('sha256');
  for (const f of files.sort()) h.update(path.relative(rust, f)).update(fs.readFileSync(f));
  return h.digest('hex').slice(0, 16);
}

if (process.argv.includes('--check')) {
  require('./rust/export-data.js');
  const have = fs.existsSync(out) && (fs.readFileSync(out, 'utf8').match(/sources ([0-9a-f]+)/) || [])[1];
  const want = sources();
  if (have !== want) { console.error(`crux-wasm.js is stale (built from ${have || 'nothing'}, sources now ${want}): node crux/build-wasm.js`); process.exit(1); }
  console.log('crux-wasm.js is up to date');
  process.exit(0);
}
require('./rust/export-data.js');
execFileSync(process.env.CARGO || require('os').homedir() + '/.cargo/bin/cargo', ['build', '--profile', 'wasm', '-p', 'crux-wasm', '--target', 'wasm32-unknown-unknown'], { cwd: rust, stdio: 'inherit' });
const wasm = fs.readFileSync(path.join(rust, 'target/wasm32-unknown-unknown/wasm/crux_wasm.wasm'));
fs.writeFileSync(out, `/* Generated by crux/build-wasm.js from rust/ (sources ${sources()}). Do not edit. */\nself.CRUX_WASM = '${wasm.toString('base64')}';\n`);
console.log(`crux-wasm.js: ${(wasm.length / 1024).toFixed(0)} KB of wasm`);
