// Read JS literals without evaluating code. Interpolations become named slots; nested templates are read too.
function quoted(source, start) {
  const quote = source[start]; let i = start + 1;
  while (i < source.length) { if (source[i] === '\\') i += 2; else if (source[i++] === quote) break; }
  const value = source.slice(start + 1, i - 1);
  if (/^[A-Z]/.test(value) && !['Enter', 'Escape'].includes(value)) add(value);
  return i;
}
function code(source, start = 0, nested = false) {
  let i = start, depth = nested ? 1 : 0;
  while (i < source.length) {
    if (source.startsWith('//', i)) { const end = source.indexOf('\n', i); i = end < 0 ? source.length : end; }
    else if (source.startsWith('/*', i)) { const end = source.indexOf('*/', i + 2); i = end < 0 ? source.length : end + 2; }
    else if (source[i] === '"' || source[i] === "'") i = quoted(source, i);
    else if (source[i] === '`') i = template(source, i);
    else if (nested && source[i] === '{') { depth++; i++; }
    else if (nested && source[i] === '}') { i++; if (--depth === 0) return i; }
    else i++;
  }
  return i;
}
function template(source, start) {
  let text = '', i = start + 1, n = 0;
  while (i < source.length && source[i] !== '`') {
    if (source[i] === '\\') { text += source.slice(i, i + 2); i += 2; }
    else if (source.startsWith('${', i)) { i = code(source, i + 2, true); text += '{arg' + n++ + '}'; }
    else text += source[i++];
  }
  if (!text.includes('<')) add(text);
  else {
    for (const m of text.matchAll(/>([^<>]+)</g)) add(m[1]);
    for (const m of text.matchAll(/(?:title|aria-label)="([^"<>]+)"/g)) add(m[1]);
  }
  return i + 1;
}
